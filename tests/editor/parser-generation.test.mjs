import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { test } from 'node:test';
import peggy from 'peggy';

const root = new URL('../../projects/core-lib/case/notifier/lib/shared/directives/conditional-show/services/', import.meta.url);
const prefix = '// @ts-nocheck\n// This file is generated by npm run generate:condition-parser. Do not edit by hand.\n';

test('checked-in condition parser matches the maintained grammar', async () => {
  const grammar = await readFile(new URL('condition.peggy', root), 'utf8');
  const actual = await readFile(new URL('condition-parser.generated.ts', root), 'utf8');
  assert.equal(actual, prefix + peggy.generate(grammar, { output: 'source', format: 'es' }));
});
