import { readFile, writeFile } from 'node:fs/promises';
import peggy from 'peggy';

const directory = new URL('../../projects/core-lib/case/notifier/lib/shared/directives/conditional-show/services/', import.meta.url);
const grammar = await readFile(new URL('condition.peggy', directory), 'utf8');
const prefix = '// @ts-nocheck\n// This file is generated by npm run generate:condition-parser. Do not edit by hand.\n';
await writeFile(new URL('condition-parser.generated.ts', directory), prefix + peggy.generate(grammar, { output: 'source', format: 'es' }));
